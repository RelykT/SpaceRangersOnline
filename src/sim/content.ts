function resist(base: Resists, add: number): Resists {
  return {
    em: Math.min(0.82, base.em + add),
    thermal: Math.min(0.82, base.thermal + add),
    kinetic: Math.min(0.82, base.kinetic + add),
    explosive: Math.min(0.82, base.explosive + add),
  };
}

